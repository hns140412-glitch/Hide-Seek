'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
globalThis.window=globalThis;
const vendored=require(path.join(root,'vendor/taky/vision-ingest.js'));
require(path.join(root,'hide-ocr-evidence-guard-v1.js'));
const V=(vendored&&vendored.buildRequest)?vendored:globalThis.TakyVisionIngest,G=globalThis.HideOcrEvidenceGuardV1;
assert.ok(V&&V.buildRequest&&V.normalizeResult,'shared vision ingest loads');
assert.ok(G,'guard loads');
const sourceId='hide-single-1';
const ingest=V.buildRequest({source:'hide-seek:single-photo-ocr',manifest:[{source_id:sourceId,mime_type:'image/jpeg',file_name:'c.jpg',size:10}]});
assert.ok(ingest.ok,'request builds');
const norm=(items,request_id=ingest.request.request_id)=>V.normalizeResult({request_id,provider:'gemini',model:'m',items});
const row=(i,o={})=>({result_id:'row-'+i,evidence_source_ids:[sourceId],provider_payload:{eng:'w'+i,kor:'k',confidence:'high'},...o});
const good=norm([row(0),row(1)]);
assert.ok(good.ok);
assert.equal(G.check(good.result,ingest.request,[sourceId]).ok,true,'clean result accepted');
const other=norm([row(0)],'someone-elses-request');
assert.ok(other.ok);assert.equal(G.check(other.result,ingest.request,[sourceId]).reason,'OCR_REQUEST_BINDING_MISMATCH');
const missing=norm([row(0,{evidence_source_ids:[]})]);
assert.ok(missing.ok);assert.equal(G.check(missing.result,ingest.request,[sourceId]).ok,false,'row without evidence rejected');
const dup=norm([row(0),row(0)]);
assert.ok(dup.ok);assert.deepEqual(G.check(dup.result,ingest.request,[sourceId]).duplicate_result_ids,['row-0']);
const foreign=norm([row(0,{evidence_source_ids:['other-photo']})]);
assert.ok(foreign.ok);assert.equal(G.check(foreign.result,ingest.request,[sourceId]).unknown.length,1);
const conf=norm([row(0,{provider_payload:{eng:'a',kor:'b',confidence:'sure!!'}})]);
assert.ok(conf.ok);assert.deepEqual(G.check(conf.result,ingest.request,[sourceId]).invalid_confidence,['row-0']);
const appJs=fs.readFileSync(path.join(root,'app.js'),'utf8');
assert.match(appJs,/HideOcrEvidenceGuardV1\.check\(normalized\.result,ingest\.request,\[sourceId\]\)/);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.ok(html.indexOf('hide-ocr-evidence-guard-v1.js')>0&&html.indexOf('hide-ocr-evidence-guard-v1.js')<html.indexOf('./app.js'));
assert.match(fs.readFileSync(path.join(root,'sw.js'),'utf8'),/hide-ocr-evidence-guard-v1\.js/);
console.log('PASS hide OCR evidence guard: request binding, per-row source, unique ids, confidence; app/page/SW wiring');
