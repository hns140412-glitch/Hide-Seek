'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
globalThis.window=globalThis;
require(path.join(root,'hide-language-evidence.js'));
const E=globalThis.HideLanguageEvidence;
assert.ok(E,'module loads');
assert.deepEqual(E.invalidRecords,[],'every record passes its own source policy');
assert.equal(E.records.rainforest.supportType,'TRANSPARENT_COMPOUND');
assert.equal(E.records.rainforest.claimsHistoricalEtymology,false,'compound does not claim historical etymology');
assert.equal(E.records.ocean.supportType,'VERIFIED_ETYMOLOGY');
assert.ok(E.records.ocean.nodes.some(n=>n.role==='ORIGIN_GUARD'),'deeper ocean origin stays held');
assert.equal(E.validateRecord('fake',{supportType:'VERIFIED_ETYMOLOGY',sourceType:'BLOG',sourceRef:'x',center:{},nodes:[]}),false,'unsourced claim rejected');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.ok(html.indexOf('hide-language-evidence.js')>0&&html.indexOf('hide-language-evidence.js')<html.indexOf('hide-english-pedagogy-v1.js'),'loads before English pedagogy');
assert.match(fs.readFileSync(path.join(root,'sw.js'),'utf8'),/hide-language-evidence\.js/);
assert.match(fs.readFileSync(path.join(root,'hide-english-pedagogy-v1.js'),'utf8'),/HideLanguageEvidence/);
console.log('PASS hide verified word origins: '+Object.keys(E.records).length+' records valid incl. rainforest/ocean; reveal + page + SW wiring');
